/** Escapes text for safe insertion into HTML text and quoted attribute values. */
export function escapeHtml(value        )         {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}
